        internal SpaceEntityGroup CopyForCelestialStep(SpaceGameComp host, SpaceEntityGroup? recycled = null)
        {
            var copy = recycled?.celestialSource == this ? recycled : (SpaceEntityGroup)MemberwiseClone();
            var containers = copy.celestialBuffers ??= new();
            var oldEntityIds = copy.entityIds; var oldSlices = copy.thrustSliceScratch; var oldManeuvers = copy.plannedManeuvers;
            var oldWhitelist = copy.orbitKeepingWhitelist; var oldIgnored = copy.ignoredGravityBodyIds;
            var oldBurn = copy.burnEnabledNetworks; var oldRendezvous = copy.rendezvousUseNetworks;
            var oldInertia = copy.inertiaScratch; var oldCombat = copy.CombatCache;
            CopyCelestialInputFieldsTo(copy);
            copy.celestialSource = this;
            copy.preparedPhysicsHost = host;
            copy.entityIds = containers.Set("entities", entityIds, oldEntityIds);
            copy.thrustSliceScratch = containers.List("slices", thrustSliceScratch, oldSlices); copy.thrustSliceScratch.Clear();
            copy.plannedManeuvers = containers.List("maneuvers", plannedManeuvers, oldManeuvers);
            copy.orbitKeepingWhitelist = orbitKeepingWhitelist == null ? null : containers.Set("whitelist", orbitKeepingWhitelist, oldWhitelist);
            copy.ignoredGravityBodyIds = ignoredGravityBodyIds == null ? null : containers.List("ignored", ignoredGravityBodyIds, oldIgnored);
            copy.burnEnabledNetworks = burnEnabledNetworks == null ? null : containers.Set("burn", burnEnabledNetworks, oldBurn);
            copy.rendezvousUseNetworks = rendezvousUseNetworks == null ? null : containers.Set("rendezvous", rendezvousUseNetworks, oldRendezvous);
            copy.inertiaScratch = oldInertia != null && !ReferenceEquals(oldInertia, inertiaScratch) ? oldInertia : null;
            if (CombatCache != null)
            {
                copy.CombatCache = containers.Choose("combat", CombatCache, oldCombat, () => new PhysicsStateCache());
                copy.CombatCache.baseTick = CombatCache.baseTick; copy.CombatCache.startPos = CombatCache.startPos; copy.CombatCache.startVel = CombatCache.startVel;
                copy.CombatCache.acc = CombatCache.acc; copy.CombatCache.jerk = CombatCache.jerk; copy.CombatCache.dt = CombatCache.dt; copy.CombatCache.offset = CombatCache.offset;
            }
            copy.cachedPropulsionAggregator = null;
            copy.cachedMapPropulsionAggregator = null;
            copy.cachedPropulsionStamp = copy.cachedMapPropulsionStamp = int.MinValue;
            return copy;
        }

